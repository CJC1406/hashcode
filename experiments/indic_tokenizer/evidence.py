"""Evidence sheet for the Indic tokenizer experiment, generated only from recorded result files (no numbers typed by hand).

Reads: results/indic_tokenizer/*/summary.json, the candidate manifests' .sha256 sidecars (local, outside Git), the tokenizer and
frozen P2c checksums, and the FLORES+ spec's approval flags. Writes results/indic_tokenizer/evidence.md and prints it.
Usage: python3 -I experiments/indic_tokenizer/evidence.py
"""
import hashlib
import json
import pathlib
import sys

sys.dont_write_bytecode = True
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
RESULTS = ROOT / "results/indic_tokenizer"
CANDIDATES = pathlib.Path("/Users/Shared/hashcode-data/indic_tokenizer/wikipedia-20261001")
SPEC = ROOT / "datasets/external_manifests/flores_plus_devtest_e707e62e.json"


def sha(p):
    return hashlib.sha256(pathlib.Path(p).read_bytes()).hexdigest()


def table(s):
    rows = ["| Group | Samples | Chars | A tokens | A per 1,000 chars | B tokens | B reduction | C tokens | C reduction | B improved / worse | Exact round trip A/B/C |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    order = [g for g in ("hi", "kn", "en", "mixed", "edge", "other") if g in s["groups"]] + [g for g in s["groups"] if g not in ("hi", "kn", "en", "mixed", "edge", "other")]
    for g in order:
        r = s["groups"][g]
        c = (f"{r['C_tokens']:,}", f"{r['C_reduction_percent']}%") if "C_tokens" in r else ("n/a", "n/a")
        rows.append(f"| {g} | {r['samples']:,} | {r['chars']:,} | {r['A_tokens']:,} | {r['A_tokens_per_1000_chars']} | {r['B_tokens']:,} | "
                    f"{r['B_reduction_percent']}% | {c[0]} | {c[1]} | {r['B_samples_improved']:,} / {r['B_samples_worse']:,} | "
                    f"{r['A_exact_round_trip']}/{r['B_exact_round_trip']}/{r.get('C_exact_round_trip', 'n/a')} of {r['samples']} |")
    return "\n".join(rows)


def main():
    spec = json.loads(SPEC.read_text())
    approvals = spec["approval"]
    lines = ["# Indic tokenizer: evidence sheet (generated by experiments/indic_tokenizer/evidence.py)", "",
             "Native **Qwen3** input-token counts. **A** = original tokenizer; **B** = A + 2,048 ByteME-derived Indic tokens; "
             "**C** = A + 2,048 words-only tokens (ablation). reduction = 100 × (A − X) / A. No model inference was run: "
             "nothing here measures model speed or quality.", "",
             "## Identity and provenance",
             f"- Tokenizer: `external/token-vldb2026/tokenizers/qwen3.json`, SHA-256 `{sha(ROOT / 'external/token-vldb2026/tokenizers/qwen3.json')}` "
             "(= Qwen/Qwen3-0.6B tokenizer.json at revision c1899de2…, apache-2.0); read by the dependency-free `hf_bpe.py` "
             "(not yet checked against the reference `tokenizers` library, which is not installed).",
             f"- Frozen P2c vocabulary (read only): SHA-256 `{sha(ROOT / 'codec/p2c/p2c_vocabulary_v1.bin')}`."]
    for name in ("candidates-bytme-k2048", "candidates-words-k2048"):
        side = CANDIDATES / f"{name}.sha256"
        if side.is_file():
            ok = side.read_text().split()[0] == sha(CANDIDATES / f"{name}.json")
            lines.append(f"- Candidate manifest `{name}.json` (outside Git): SHA-256 `{side.read_text().split()[0]}` ({'verified' if ok else 'MISMATCH'}).")
        else:
            lines.append(f"- Candidate manifest `{name}.json`: not present on this machine.")
    lines += ["- Candidates were selected on the Wikipedia hiwiki + knwiki 20261001 **training split** only (held-out documents skipped).", "",
              "## Independent evaluation (FLORES+ devtest)",
              f"- **Not run.** Spec `{SPEC.name}` approvals: " + ", ".join(f"{k}={v}" for k, v in approvals.items()) +
              f"; decontamination={spec['decontamination']}. The evaluator refuses until the owner sets them.",
              "- The proposed target (>= 20% fewer native tokens than A for Hindi and Kannada) is therefore **unverified on independent data**.", ""]
    for d in sorted(RESULTS.glob("*/summary.json")):
        s = json.loads(d.read_text())
        lines += [f"## {d.parent.name}", f"**{s['label']}**", ""]
        src = s["source"]
        if src.get("files"):
            lines.append("Source files: " + "; ".join(f"`{f.get('file') or f.get('path')}` SHA-256 `{f.get('sha256', '')[:16]}…`" for f in src["files"]) +
                         (f"; {src['heldout_documents']} held-out documents ({src['split']})." if "heldout_documents" in src else "."))
        elif src.get("file"):
            lines.append(f"Source file: `{src['file']}` (hand-written fixture sentences).")
        lines += ["", table(s), "",
                  "Tokenization throughput of the Python prototype (not model inference; not representative of the Rust library): " +
                  ", ".join(f"{k} {v['chars_per_second']:,} chars/s" for k, v in s["throughput_python_prototype"].items()), ""]
    logs = sorted((RESULTS / "test_logs").glob("*.txt")) if (RESULTS / "test_logs").exists() else []
    if logs:
        lines += ["## Test logs (results/indic_tokenizer/test_logs/)"]
        for p in logs:
            last = [l for l in p.read_text(errors="replace").splitlines() if l.strip()]
            summary = next((l for l in reversed(last) if l.startswith(("OK", "FAILED", "All tests passed", "test cases:")) or "assertions" in l), last[-1] if last else "")
            lines.append(f"- `{p.name}`: {summary.strip()}")
        lines.append("")
    lines += ["The `cpp_roundtrip` (7) and `cpp_upstream` (2) failures are the known, pre-existing upstream sgtt failures documented in "
              "docs/phase0_baseline_findings.md; they are unchanged.", ""]
    lines += ["## Limitations",
              "- The held-out split is the **same source** as the training text (Wikipedia; shared templates and topics): optimistic, not independent.",
              "- Hand-written fixture sentences are illustrative only.",
              "- English: extension tokens contain only Devanagari/Kannada characters, so text without them is tokenized exactly as by A "
              "(tested). The held-out 'en' group is Latin-script lines of the Hindi/Kannada wikis, not an English benchmark.",
              "- Token-count reduction does not show the model can use the new tokens: embeddings and output rows are untrained (model stage blocked)."]
    text = "\n".join(lines) + "\n"
    (RESULTS / "evidence.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
